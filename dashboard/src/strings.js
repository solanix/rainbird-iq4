const TABLES = { en: EN };

export function t(language, key, params = {}) {
  const table = TABLES[String(language ?? "en").split("-")[0]] ?? EN;
  const template = table[key] ?? EN[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => (name in params ? String(params[name]) : `{${name}}`));
}
