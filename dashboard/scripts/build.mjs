// Concatenate the ES modules into one file for /local/ so a single versioned resource
// URL busts the browser cache for all of it. No dependencies: the sources use only
// top-level named imports/exports, which this strips in dependency order.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ORDER = ["strings.js", "model.js", "styles.js", "view.js", "card.js"];

export function bundle() {
  const parts = ORDER.map((name) => {
    const source = readFileSync(join(root, "src", name), "utf8")
      .replace(/^import\s*\{[^}]*\}\s*from\s*"[^"]+";\s*$/gms, "")
      .replace(/^export\s+(?=(const|function|class|async function)\b)/gm, "");
    if (/^\s*(import|export)\b/m.test(source)) throw new Error(`${name}: unsupported import/export form`);
    return `// ---- ${name}\n${source.trim()}\n`;
  });
  const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  return `// Rain Bird IQ4 card ${version}. Generated by scripts/build.mjs; edit src/ instead.\n(() => {\n"use strict";\n${parts.join("\n")}})();\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = join(root, "dist", "rainbird-iq4-card.js");
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, bundle());
  console.log(`wrote ${out}`);
}
